function _getContexts(q) {
  const all = [...q.tags, ...q.text.split(/[\s/()]/g)].join(' ');
  const ctxs = [];
  for (const [ctx, keywords] of Object.entries(PF_CONTEXT_MAP)) {
    if (keywords.some(kw => all.includes(kw))) ctxs.push(ctx);
  }
  return ctxs;
}

function getNextQuestions(selectedQ) {
  const nextDepth = selectedQ.depth + 1;
  if (nextDepth > 6) return [];
  const candidates = PF_QUESTIONS.filter(q => q.depth === nextDepth);
  
  // 1차: nextTags 직접 매칭
  const tagMatch = candidates.filter(q =>
    q.tags.some(t => selectedQ.nextTags.includes(t))
  );
  if (tagMatch.length >= 4) return tagMatch;
  
  // 2차: context 기반 보충
  const selCtx = _getContexts(selectedQ);
  const ctxMatch = candidates.filter(q =>
    !tagMatch.includes(q) && _getContexts(q).some(c => selCtx.includes(c))
  );
  const combined = [...tagMatch, ...ctxMatch];
  if (combined.length >= 4) return combined;
  
  // 3차: 그래도 부족하면 해당 depth의 범용 질문 보충
  if (combined.length >= 3) return combined;
  
  const rest = candidates.filter(q => !combined.includes(q));
  // situation에 '기본','점검','전반' 포함하거나, 아무거나 추가
  const general = rest.filter(q =>
    q.situation && /기본|점검|전반|종합/.test(q.situation)
  );
  const result = [...combined, ...general];
  if (result.length >= 3) return result.slice(0, Math.max(result.length, 6));
  
  // 4차: 최후 — 아무거나 채움
  return [...result, ...rest.slice(0, 3 - result.length)];
}

function getStartQuestions() {
  return PF_QUESTIONS.filter(q => q.depth === 1);
}
