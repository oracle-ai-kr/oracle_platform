/** 이름풀이 */
function analyzeName(name, strokeData, saju) {
  const oh = {나무:0,불:0,흙:0,쇠:0,물:0};
  [saju.연주,saju.월주,saju.일주,saju.시주].forEach(p=>{
    const t=오행Map[p.천간]; if(t)oh[t]++;
    const e=지지오행[p.지지]; if(e)oh[e]++;
  });
  const sorted=Object.entries(oh).sort((a,b)=>b[1]-a[1]);
  const weakest = sorted[sorted.length-1][0];

  // 이름 오행 분석
  const nameOhCounts = {};
  strokeData.forEach(s => { nameOhCounts[s.oh] = (nameOhCounts[s.oh]||0) + 1; });
  const mainNameOh = Object.entries(nameOhCounts).sort((a,b)=>b[1]-a[1])[0][0];

  let result = `🔤 이름 소리(음)의 에너지\n\n`;
  result += `"${name}"이라는 이름을 불렀을 때, `;
  result += 이름오행해석[mainNameOh].소리 + '\n\n';

  result += `✨ 획수와 오행의 의미\n\n`;
  strokeData.forEach(s => {
    result += `▸ "${s.char}" — ${s.strokes}획 (${오행이모지[s.oh]} ${s.oh})\n`;
  });
  result += `\n이름 전체의 오행 조합: `;
  result += Object.entries(nameOhCounts).map(([k,v])=>`${오행이모지[k]}${k} ${v}개`).join(', ');
  result += `\n\n${이름오행해석[mainNameOh].의미}\n\n`;

  result += `🌟 사주와 이름의 조화\n\n`;
  if(weakest === mainNameOh) {
    result += pick(이름사주조화.보완).replace(/{오행}/g, mainNameOh) + '\n\n';
  } else if(oh[mainNameOh] >= 3) {
    result += pick(이름사주조화.강화).replace(/{오행}/g, mainNameOh) + '\n\n';
  } else {
    result += pick(이름사주조화.조화) + '\n\n';
  }

  result += `💫 이 이름이 가진 운의 특성\n\n`;
  result += `"${name}"이라는 이름은 ${mainNameOh} 기운의 영향을 받아 `;
  const luck = 행운포인트[mainNameOh];
  result += `${luck.색깔} 계열이 행운의 색이고, ${luck.방위} 방향에서 좋은 에너지를 받습니다. `;
  result += `${luck.활동} 등의 활동이 이름의 에너지를 더욱 활성화시켜줍니다.\n\n`;

  result += `🌱 이 이름으로 살아갈 때의 조언\n\n`;
  result += `"${name}"이라는 이름의 에너지를 최대한 활용하려면, 이름이 가진 ${mainNameOh} 기운을 의식하며 생활하세요. `;
  result += `이름은 매일 불리는 에너지이기에 그 영향력이 생각보다 큽니다. 자신의 이름을 사랑하고, 이름이 가진 긍정적 에너지를 믿으세요. ✨`;

  return result;
}

