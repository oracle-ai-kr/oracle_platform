/** 사주 전체 분석 (장기운) */
function analyzeSaju(saju, year, month, day, hour, gender) {
  const tg = saju.일주.천간;
  const oh = {나무:0,불:0,흙:0,쇠:0,물:0};
  [saju.연주,saju.월주,saju.일주,saju.시주].forEach(p=>{
    const t=오행Map[p.천간]; if(t)oh[t]++;
    const e=지지오행[p.지지]; if(e)oh[e]++;
  });
  const total=Object.values(oh).reduce((a,b)=>a+b,0);
  const sorted=Object.entries(oh).sort((a,b)=>b[1]-a[1]);
  const strongest=sorted[0][0], weakest=sorted[sorted.length-1][0];
  const ilganOh = 오행Map[tg];

  // 성격
  const personality = pick(천간성격[tg]);

  // 오행 조합 분석
  let ohAnalysis = '';
  if(sorted[0][1]>=4) ohAnalysis = pick(오행조합해석.강[strongest]);
  else if(sorted[sorted.length-1][1]===0) ohAnalysis = pick(오행조합해석.약[weakest]);
  else ohAnalysis = pick(오행조합해석.균형);

  // 직업/재물
  const career = pick(오행직업[ilganOh].직업);
  const wealth = pick(오행직업[ilganOh].재물);

  // 연애
  const love = pick(연애해석[tg]);

  // 올해 운세
  const thisYear = new Date().getFullYear();
  const yearTG = ['갑','을','병','정','무','기','경','신','임','계'][(thisYear-4)%10];
  const yearOh = 오행Map[yearTG];
  const yearFortune = pick(세운해석[yearOh]);

  // 강점/약점
  const strengths = 강점약점[tg].강;
  const weaknesses = 강점약점[tg].약;

  // 건강
  const health = pick(건강해석[ilganOh]);

  // 행운
  const luck = 행운포인트[ilganOh];

  let result = `🌟 타고난 기질과 성격의 핵심\n\n${personality}\n\n${ohAnalysis}\n\n`;
  result += `💼 직업과 재물의 흐름\n\n${career}\n\n${wealth}\n\n`;
  result += `❤️ 인연과 감정의 패턴\n\n${love}\n\n`;
  result += `📅 올해(${thisYear}년) 전반적인 흐름\n\n${yearFortune}\n\n`;
  result += `💪 강점과 보완할 점\n\n✅ 강점:\n`;
  strengths.forEach(s => result += `• ${s}\n`);
  result += `\n⚠️ 보완할 점:\n`;
  weaknesses.forEach(w => result += `• ${w}\n`);
  result += `\n🏥 건강 관리 포인트\n\n${health}\n\n`;
  result += `🎯 행운 포인트\n• 행운의 색: ${luck.색깔}\n• 행운의 방위: ${luck.방위}\n• 행운의 숫자: ${luck.숫자}\n• 행운의 시간: ${luck.시간}\n• 보완 음식: ${luck.음식}\n• 추천 활동: ${luck.활동}`;

  return result;
}

